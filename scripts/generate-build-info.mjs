import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const buildTime = new Date().toISOString();

function getCommitSha() {
  try {
    return execSync("git rev-parse --short HEAD", {
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "unknown";
  }
}

const version = `${getCommitSha()}-${buildTime}`;
const appDir = path.resolve("./src/app");
const assetsDir = path.resolve("./src/assets");

fs.mkdirSync(appDir, { recursive: true });
fs.mkdirSync(assetsDir, { recursive: true });

fs.writeFileSync(
  path.join(appDir, "build-info.generated.ts"),
  `/* AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY. */\n/* Generated by scripts/generate-build-info.mjs */\n\nexport const CURRENT_BUILD_VERSION = ${JSON.stringify(version)};\n`,
  "utf-8",
);

fs.writeFileSync(
  path.join(assetsDir, "app-version.json"),
  `${JSON.stringify({ version, buildTime }, null, 2)}\n`,
  "utf-8",
);

console.log(`Generated build version ${version}`);
